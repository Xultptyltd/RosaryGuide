package app.rosaryguide.android.di

import android.content.Context
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import app.rosaryguide.android.icons.AppIconController
import app.rosaryguide.core.data.auth.AuthBackend
import app.rosaryguide.core.data.auth.AuthStore
import app.rosaryguide.core.data.prefs.SettingsStore
import app.rosaryguide.core.data.session.SessionStore
import app.rosaryguide.core.data.sync.AccountDeletion
import app.rosaryguide.core.data.sync.AccountRemote
import app.rosaryguide.core.data.sync.AccountSync
import app.rosaryguide.core.data.sync.DataStoreKeyValueStore
import app.rosaryguide.notifications.ReminderScheduler
import app.rosaryguide.sync.FirebaseAuthBackend
import app.rosaryguide.sync.FirestoreAccountRemote
import dagger.Module
import dagger.Provides
import dagger.hilt.InstallIn
import dagger.hilt.android.qualifiers.ApplicationContext
import dagger.hilt.components.SingletonComponent
import javax.inject.Qualifier
import javax.inject.Singleton
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob

@Qualifier
@Retention(AnnotationRetention.BINARY)
annotation class AppScope

/** Firebase Auth (Google) and Firestore account sync (M5). */
@Module
@InstallIn(SingletonComponent::class)
object AccountModule {
    @Provides
    @Singleton
    @AppScope
    fun provideAppScope(): CoroutineScope = CoroutineScope(SupervisorJob() + Dispatchers.Main.immediate)

    @Provides
    @Singleton
    fun provideAuthBackend(@ApplicationContext context: Context): AuthBackend {
        // Generated by the google-services plugin from the OAuth web client (client_type 3).
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        val webClientId = if (id != 0) context.getString(id) else ""
        return FirebaseAuthBackend(context, webClientId)
    }

    @Provides
    @Singleton
    fun provideAuthStore(backend: AuthBackend, @AppScope scope: CoroutineScope): AuthStore = AuthStore(backend, scope)

    @Provides
    @Singleton
    fun provideAccountRemote(): AccountRemote = FirestoreAccountRemote()

    @Provides
    @Singleton
    fun provideAccountSync(
        settingsStore: SettingsStore,
        sessionStore: SessionStore,
        dataStore: DataStore<Preferences>,
        remote: AccountRemote,
        @AppScope scope: CoroutineScope,
        reminderScheduler: ReminderScheduler,
        appIconController: AppIconController,
    ): AccountSync = AccountSync(
        settings = settingsStore,
        session = sessionStore,
        store = DataStoreKeyValueStore(dataStore),
        remote = remote,
        scope = scope,
        onPreferencesApplied = { previous, current ->
            if (previous.notificationPlanSettings != current.notificationPlanSettings) {
                reminderScheduler.reschedule(current)
            }
            // Swapping launcher aliases under a visible activity can close it; wait for the background.
            if (previous.appIcon != current.appIcon) appIconController.pending = current.appIcon
        },
    )

    @Provides
    @Singleton
    fun provideAccountDeletion(auth: AuthStore, sync: AccountSync): AccountDeletion = AccountDeletion(auth, sync)
}
